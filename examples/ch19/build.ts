// Bundle ch19/bundle/main.ts the way `vite build` does, and print the files
// it would write. Run from the examples folder: node ch19/build.ts
import { build, type Rolldown } from 'vite'

const result = (await build({
  configFile: false, // ignore examples/vite.config.ts
  logLevel: 'silent',
  build: {
    write: false, // keep the output in memory instead of writing dist/
    minify: false, // readable output (a real build minifies)
    rolldownOptions: { input: 'ch19/bundle/main.ts' },
  },
})) as Rolldown.RolldownOutput

for (const file of result.output) {
  if (file.type !== 'chunk') continue
  console.log(`===== ${file.fileName} =====`)
  // Each module's code starts with a "// <file name>" comment. Skip the code
  // that Vite generates itself (marked "// \0…"), such as its import() helper.
  let hidden = false
  for (const line of file.code.split('\n')) {
    if (line.startsWith('// ')) {
      hidden = line.startsWith('// \\0')
      if (hidden) console.log(`// ${line.slice(5)}: code generated by Vite, not shown`)
    }
    if (!hidden) console.log(line)
  }
}
